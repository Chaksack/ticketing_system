import type { Database } from 'db0'
import { AsyncLocalStorage } from 'node:async_hooks'
import process from 'node:process'
import { createDatabase } from 'db0'
import postgresql from 'db0/connectors/postgresql'

/**
 * Multi-company tenancy: every company (organisation) has its own Postgres database. The
 * original database is the HOME organisation — Canopy's own workspace — and also holds the
 * control plane (server/utils/controlPlane.ts: which companies exist, who belongs where).
 *
 * All app code reads and writes through `useTenantDb()`, which resolves the current company:
 *   1. an explicit `runWithTenant(orgId, fn)` scope (scheduled jobs, provisioning, sign-in), else
 *   2. `event.context.orgId` on the current request (set by server/middleware/00.tenant.ts from
 *      the session, or by a handler from a portal slug / API key / token), else
 *   3. the home organisation.
 */

export const HOME_ORG_ID = 'canopy'

const tenantScope = new AsyncLocalStorage<{ orgId: string }>()

/** Runs `fn` with `orgId` as the current company, whatever request (if any) it's part of. */
export function runWithTenant<T>(orgId: string, fn: () => T): T {
  return tenantScope.run({ orgId }, fn)
}

export function currentOrgId(): string {
  const scoped = tenantScope.getStore()?.orgId
  if (scoped)
    return scoped
  try {
    const fromRequest = useEvent()?.context?.orgId as string | undefined
    if (fromRequest)
      return fromRequest
  }
  catch {
    // Not inside a request (plugin interval, startup) — fall through to the home org.
  }
  return HOME_ORG_ID
}

/** Sets the company for the rest of this request (e.g. after resolving a portal slug or API key). */
export function setRequestOrg(event: { context: Record<string, any> }, orgId: string) {
  event.context.orgId = orgId
}

// ── Database names & connections ───────────────────────────────────────────

/** Org ids are generated by us (lowercase letters, digits, hyphens) — still validated, since they end up in SQL identifiers. */
export function assertSafeOrgId(orgId: string) {
  if (!/^[a-z0-9][a-z0-9-]{1,40}$/.test(orgId))
    throw createError({ statusCode: 400, statusMessage: 'Invalid organisation id' })
}

export function tenantDatabaseName(orgId: string) {
  assertSafeOrgId(orgId)
  return `canopy_t_${orgId.replace(/-/g, '_')}`
}

function baseDatabaseUrl(): string {
  const url = process.env.DATABASE_URL
  if (!url)
    throw new Error('DATABASE_URL is not set')
  return url
}

/** Same server and credentials as the main database, a different database name. */
export function tenantDatabaseUrl(orgId: string): string {
  const url = new URL(baseDatabaseUrl())
  url.pathname = `/${tenantDatabaseName(orgId)}`
  return url.toString()
}

const tenantConnections = new Map<string, Database>()

export function databaseForOrg(orgId: string): Database {
  if (orgId === HOME_ORG_ID)
    return useDatabase()
  let db = tenantConnections.get(orgId)
  if (!db) {
    db = createDatabase(postgresql({ url: tenantDatabaseUrl(orgId) }))
    tenantConnections.set(orgId, db)
  }
  return db
}

/** The current company's database. Use this everywhere app data is read or written. */
export function useTenantDb(): Database {
  return databaseForOrg(currentOrgId())
}

/** The control plane (company registry, directory, staff-console data) — always the main database. */
export function useControlDb(): Database {
  return useDatabase()
}

/** Drops a cached connection (after deleting a company's database). */
export function forgetTenantConnection(orgId: string) {
  tenantConnections.delete(orgId)
}
